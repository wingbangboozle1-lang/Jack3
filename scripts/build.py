#!/usr/bin/env python3
"""Compatibility entry point.

Older tooling and README instructions call ``python3 scripts/build.py``.  The
canonical site is now generated by a single generator so that no stale builder can
silently overwrite published pages.
"""
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
raise SystemExit(subprocess.call([sys.executable, str(ROOT / "scripts/build_canonical.py")], cwd=str(ROOT)))
